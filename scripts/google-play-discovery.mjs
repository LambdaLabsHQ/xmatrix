#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { writeOrCheckGenerated } from "./pinned-catalog-output.mjs";

/*
 * The pinned Google Play Android Developer API discovery document
 * (vendor/google-play) becomes the Hub's operation catalog and request
 * schemas. Nothing remote is fetched here or at runtime.
 */
const root = new URL("../", import.meta.url);
const source = new URL("vendor/google-play/discovery.json", root);
const output = new URL("packages/hub/src/connectors/generated/", root);
const raw = await readFile(source, "utf8");
const discovery = JSON.parse(raw);
if (discovery.name !== "androidpublisher" || discovery.version !== "v3" || discovery.rootUrl !== "https://androidpublisher.googleapis.com/") {
  throw new Error("Not the androidpublisher v3 discovery document");
}
const SCOPE = "https://www.googleapis.com/auth/androidpublisher";
const brief = value => typeof value === "string" ? value.replace(/\s+/gu, " ").trim().slice(0, 300) : undefined;
const schemaKeys = new Set(["$ref", "type", "format", "properties", "items", "enum", "additionalProperties", "readOnly", "deprecated", "description", "pattern"]);

function schema(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return value;
  if (value.$ref !== undefined && !discovery.schemas[value.$ref]) throw new Error(`Missing schema: ${value.$ref}`);
  return Object.fromEntries(Object.entries(value).filter(([key]) => schemaKeys.has(key)).map(([key, item]) => [key,
    key === "properties" ? Object.fromEntries(Object.entries(item).map(([name, field]) => [name, schema(field)]))
      : key === "description" ? brief(item) : typeof item === "object" ? schema(item) : item]));
}

const operations = {};
(function walk(resource) {
  for (const method of Object.values(resource.methods ?? {})) {
    const id = method.id.replace(/^androidpublisher\./u, "");
    if (operations[id] || id === method.id) throw new Error(`Duplicate or foreign method ${method.id}`);
    if (!method.scopes?.includes(SCOPE)) throw new Error(`${id} needs another OAuth scope`);
    if (!["GET", "POST", "PUT", "PATCH", "DELETE"].includes(method.httpMethod)) throw new Error(`${id} uses ${method.httpMethod}`);
    const parameters = Object.entries(method.parameters ?? {}).map(([name, parameter]) => {
      if (!["path", "query"].includes(parameter.location)) throw new Error(`${id}.${name} is in ${parameter.location}`);
      const single = schema({ type: parameter.type, format: parameter.format, enum: parameter.enum, pattern: parameter.pattern });
      return { name, in: parameter.location, required: parameter.required === true,
        ...(parameter.location === "path" && method.path.includes(`{+${name}}`) ? { reserved: true } : {}),
        schema: parameter.repeated ? { type: "array", items: single } : single };
    });
    const resumable = method.mediaUpload?.protocols?.resumable?.path;
    // The Hub derives the upload URL from the validated method path; the two must agree.
    if (resumable && resumable !== `/resumable/upload/${method.path}`) throw new Error(`${id} uploads to an unexpected path`);
    operations[id] = { path: `/${method.path}`, method: method.httpMethod, deprecated: method.deprecated === true,
      description: brief(method.description), parameters,
      ...(method.request ? { body: schema(method.request) } : {}),
      ...(method.response ? { response: method.response.$ref } : {}),
      ...(resumable ? { upload: { path: resumable, maxSize: Number(method.mediaUpload.maxSize), accept: method.mediaUpload.accept } } : {}),
      ...(method.supportsMediaDownload ? { download: true } : {}) };
  }
  for (const child of Object.values(resource.resources ?? {})) walk(child);
})(discovery);

const schemas = Object.fromEntries(Object.entries(discovery.schemas).map(([name, value]) => [name, schema(value)]));
const catalog = { revision: discovery.revision, sha256: createHash("sha256").update(raw).digest("hex"), operations, schemas };
const ids = Object.keys(operations).sort();
const generated = {
  "google-play.json": JSON.stringify(catalog) + "\n",
  "google-play.d.ts": `/* Generated by scripts/google-play-discovery.mjs from vendor/google-play/discovery.json. */\nexport type GooglePlayOperationId =\n${ids.map(id => `  | ${JSON.stringify(id)}`).join("\n")};\n`,
};
const outcome = await writeOrCheckGenerated(output, generated, "pnpm play:generate");
// Comparing a newly downloaded discovery document never replaces the pinned authority.
const comparison = process.argv.indexOf("--compare");
if (comparison !== -1) {
  const next = JSON.parse(await readFile(process.argv[comparison + 1], "utf8"));
  const found = {};
  (function walk(resource) {
    for (const method of Object.values(resource.methods ?? {})) found[method.id.replace(/^androidpublisher\./u, "")] = method.deprecated === true;
    for (const child of Object.values(resource.resources ?? {})) walk(child);
  })(next);
  console.log(JSON.stringify({ revision: next.revision, added: Object.keys(found).filter(id => !operations[id]),
    removed: ids.filter(id => !(id in found)), deprecated: Object.keys(found).filter(id => found[id] && !operations[id]?.deprecated) }, null, 2));
}
console.log(`Google Play ${catalog.revision}: ${ids.length} operations; ${outcome}`);
